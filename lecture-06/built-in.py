numbers = [4, 2, 9, 1, 5, 6]

length = len(numbers)
print(f"The length of the list is: {length}")  # Output: 6

total_sum = sum(numbers)
print(f"The sum of the list is: {total_sum}")  # Output: 27

max_value = max(numbers)
print(f"The maximum value in the list is: {max_value}")  # Output: 9

min_value = min(numbers)
print(f"The minimum value in the list is: {min_value}")  # Output: 1

sorted_numbers = sorted(numbers)
print(f"Sorted list: {sorted_numbers}")  # Output: [1, 2, 4, 5, 6, 9]    
